import { readFile, readdir, access } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const root = new URL("../extension/", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("manifest.json", root), "utf8"));
for (const path of [manifest.background.service_worker, "cover.html", "cover.css", "src/cover.js", "parking.html", "src/parking.js", "icons/sites/canvas.png", ...Object.values(manifest.icons)]) await access(new URL(path, root));
for (const file of await readdir(new URL("src/", root))) if (file.endsWith(".js")) execFileSync(process.execPath, ["--check", join(fileURLToPath(root), "src", file)]);
if (manifest.host_permissions || manifest.content_scripts) throw new Error("Unexpected page access");
if (manifest.action.default_popup || manifest.side_panel || manifest.chrome_url_overrides) throw new Error("Stacks must operate in the native tab strip without a manager popup or side panel");
console.log("Manifest, referenced files, JavaScript syntax and permission scope checked.");
